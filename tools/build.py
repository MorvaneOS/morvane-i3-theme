#!/usr/bin/env python3
"""Builds the MorvaneOS i3 theme: i3's default config with the MorvaneOS look.

    python tools/build.py [path/to/i3/config]

Needs only Python. The argument is i3's default config, /etc/i3/config from the
i3-wm package (the default path). Output goes to config/ and skel/; commit it, it's
what the package installs.

i3 has no include directory in its default config, and /etc/i3/config is i3-wm's,
so the package installs a themed copy of it (/usr/share/morvane-i3-theme/config),
and new users get a ~/.config/i3/config that includes it. That keeps them on the
current theme after package updates, lets them add their own settings below the
include, and skips i3's first-run config wizard.
"""

import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BASE = Path(sys.argv[1]) if len(sys.argv) > 1 else Path('/etc/i3/config')
INSTALLED = '/usr/share/morvane-i3-theme/config'

# Keep in step with the window colours in morvane-gtk-theme
PASTEL = '#F4A6C6'
NIGHT = '#120C16'
PAPER = '#F5EEF3'
WHITE = '#FFFFFF'
ACTIVE_BG = '#1A1220'
INACTIVE_BG = '#150F1A'
BORDER = '#2A1C32'
SELECTED = '#4A3552'
MUTED = '#A898AC'
DIM = '#8F7F96'
URGENT = '#F0506E'
URGENT_BG = '#B3261E'

WALLPAPER = '/usr/share/backgrounds/morvaneos/twilight.png'

BAR = f'''\
bar {{
        status_command i3status
        colors {{
                background {ACTIVE_BG}
                statusline {PAPER}
                separator {BORDER}
                #                  border   background text
                focused_workspace  {PASTEL} {PASTEL}    {NIGHT}
                active_workspace   {SELECTED} {SELECTED}    {PAPER}
                inactive_workspace {ACTIVE_BG} {ACTIVE_BG}    {MUTED}
                urgent_workspace   {URGENT} {URGENT_BG}    {WHITE}
                binding_mode       {SELECTED} {SELECTED}    {PAPER}
        }}
}}
'''

THEME = f'''
# ---- MorvaneOS look, added by morvane-i3-theme ----

exec --no-startup-id xwallpaper --zoom {WALLPAPER}

# The focused window has a Pastel Pink border as well as brighter title text, so it
# isn't told apart by colour alone.
#                       border    background text     indicator child_border
client.focused          {PASTEL}  {ACTIVE_BG}    {PAPER}  {PASTEL}  {PASTEL}
client.focused_inactive {BORDER}  {ACTIVE_BG}    {MUTED}  {BORDER}  {BORDER}
client.unfocused        {BORDER}  {INACTIVE_BG}    {DIM}  {BORDER}  {BORDER}
client.urgent           {URGENT}  {URGENT_BG}    {WHITE}  {URGENT}  {URGENT}
client.background       {NIGHT}
'''

SKEL = f'''\
# Your i3 config. The MorvaneOS default, i3's own defaults in the MorvaneOS look, comes
# from morvane-i3-theme and follows its updates. Add your own settings below it; later
# lines override earlier ones. To start from a full copy instead, replace the include
# with the contents of {INSTALLED}.
include {INSTALLED}
'''


def themed(base: str) -> str:
	bar = 'bar {\n        status_command i3status\n}\n'
	if bar not in base:
		sys.exit("i3's default bar block has changed; update BAR in tools/build.py")
	# The config wizard, and the comment block above it, go: the wizard offers to write
	# ~/.config/i3/config, which new users already have
	lines = base.replace(bar, BAR).splitlines(keepends=True)
	try:
		end = lines.index('exec i3-config-wizard\n')
		start = next(i for i in range(end - 1, -1, -1) if 'i3-config-wizard' in lines[i] and lines[i - 1].startswith('####')) - 1
	except (ValueError, StopIteration):
		sys.exit("i3's default config no longer runs the config wizard the same way; check tools/build.py")
	body = ''.join(lines[:start] + lines[end + 1 :])
	header = '# i3 default config with the MorvaneOS look: generated by tools/build.py in morvane-i3-theme.\n\n'
	return header + body.rstrip('\n') + '\n' + THEME


def build() -> None:
	if not BASE.is_file():
		sys.exit(f"i3's default config not found: {BASE} (pass the path to /etc/i3/config from i3-wm)")
	for folder in ('config', 'skel'):
		shutil.rmtree(ROOT / folder, ignore_errors=True)
	(ROOT / 'config').mkdir()
	(ROOT / 'config' / 'config').write_text(themed(BASE.read_text()))
	(ROOT / 'skel').mkdir()
	(ROOT / 'skel' / 'config').write_text(SKEL)
	print('Built the i3 config.')


if __name__ == '__main__':
	build()
